export const FONT_HEIGHT = 7;
export const FONT_CHARS = Object.keys(G);

/** Uppercase, turn "<3" and heart emoji into ♥, and drop characters the font can't draw. */
export function normalizeText(input: string): string {
  return input
    .toUpperCase()
    .replace(/<3/g, "♥")
    .replace(/[❤♡💖💕💗💓]/gu, "♥")
    .replace(/️/g, "")
    .split("")
    .filter((ch) => G[ch])
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

export function glyphsFor(text: string): Bitmap[] {
  return normalizeText(text)
    .split("")
    .map((ch) => G[ch]);
}

/** Rows a word takes along the bracelet, with `spacing` empty rows between letters. */
export function textLength(text: string, spacing = 1): number {
  const glyphs = glyphsFor(text);
  if (!glyphs.length) return 0;
  return glyphs.reduce((sum, g) => sum + g[0].length, 0) + spacing * (glyphs.length - 1);
}
